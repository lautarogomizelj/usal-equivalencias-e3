-- Sprint 8: la campana replica los avisos que salen por mail (RF-ESTADO-002, contrato §2.21 y §8.2).

CREATE TABLE notificaciones (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  destinatario_tipo VARCHAR(20)  NOT NULL,  -- USUARIO o ASPIRANTE
  destinatario_id   INTEGER      NOT NULL,
  solicitud_id      INTEGER REFERENCES solicitudes (id) ON DELETE CASCADE,  -- Destino del link
  titulo            VARCHAR(255) NOT NULL,
  mensaje           TEXT         NOT NULL,
  leida             BOOLEAN      NOT NULL DEFAULT FALSE,
  fecha_creacion    TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_notificaciones_destinatario ON notificaciones (destinatario_tipo, destinatario_id, leida);
