-- Tablas base del Hito 1: Requisitos v12 §5, RF-ESTADO-003, RF-ADMIN-002 y RF-AUDIT-001.
-- Los campos marcados "Propuesta" salen del contrato de la API (§2) y todavía se pueden ajustar.

CREATE TABLE roles (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo      VARCHAR(50)  NOT NULL UNIQUE,
  nombre      VARCHAR(255) NOT NULL,
  descripcion TEXT,
  activo      BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE usuarios (
  id                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email                   VARCHAR(255) NOT NULL UNIQUE,
  nombre                  VARCHAR(255) NOT NULL,
  rol_id                  INTEGER      NOT NULL REFERENCES roles (id),
  activo                  BOOLEAN      NOT NULL DEFAULT TRUE,
  intentos_login_fallidos INTEGER      NOT NULL DEFAULT 0,
  bloqueado_hasta         TIMESTAMPTZ,
  fecha_creacion          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  fecha_ultimo_login      TIMESTAMPTZ,
  telefono                VARCHAR(20),   -- Propuesta
  avatar                  VARCHAR(50),   -- Propuesta
  google_sub              VARCHAR(255),  -- Propuesta
  password_hash           VARCHAR(255)   -- Propuesta: solo Admin
);

CREATE INDEX idx_usuarios_rol ON usuarios (rol_id);

CREATE TABLE aspirantes (
  id                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email                   VARCHAR(255) NOT NULL UNIQUE,
  password_hash           VARCHAR(255) NOT NULL,
  nombre                  VARCHAR(255) NOT NULL,
  telefono                VARCHAR(20),
  dni                     VARCHAR(20)  NOT NULL UNIQUE,
  email_validado          BOOLEAN      NOT NULL DEFAULT FALSE,
  intentos_login_fallidos INTEGER      NOT NULL DEFAULT 0,
  bloqueado_hasta         TIMESTAMPTZ,
  activo                  BOOLEAN      NOT NULL DEFAULT TRUE,
  fecha_creacion          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  fecha_ultimo_login      TIMESTAMPTZ,
  avatar                  VARCHAR(50)    -- Propuesta
);

CREATE TABLE carreras (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo         VARCHAR(50)  NOT NULL UNIQUE,
  nombre         VARCHAR(255) NOT NULL,
  facultad       VARCHAR(255),
  descripcion    TEXT,
  activo         BOOLEAN      NOT NULL DEFAULT TRUE,
  fecha_creacion TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE TABLE estados (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo      VARCHAR(50)  NOT NULL UNIQUE,
  nombre      VARCHAR(255) NOT NULL,
  descripcion TEXT,
  es_terminal BOOLEAN      NOT NULL DEFAULT FALSE,
  activo      BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE auditoria_sistema (
  id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  timestamp              TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  usuario_id             INTEGER REFERENCES usuarios (id),
  usuario_email          VARCHAR(255) NOT NULL,
  accion                 VARCHAR(100) NOT NULL,
  entidad                VARCHAR(100) NOT NULL,
  entidad_id             INTEGER,
  estado_codigo_anterior VARCHAR(50) REFERENCES estados (codigo),
  estado_codigo_nuevo    VARCHAR(50) REFERENCES estados (codigo),
  detalles               JSONB,
  comentarios            TEXT,
  ip_origen              VARCHAR(45)
);

CREATE INDEX idx_auditoria_timestamp ON auditoria_sistema (timestamp DESC);
CREATE INDEX idx_auditoria_usuario ON auditoria_sistema (usuario_id);
CREATE INDEX idx_auditoria_entidad ON auditoria_sistema (entidad, entidad_id);
