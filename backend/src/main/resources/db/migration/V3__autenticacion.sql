-- Sprint 2: sesiones, códigos de verificación (contrato de la API §2.19 y §2.20) y permisos por carrera
-- (Requisitos v12 §5), que necesita Sesion.carrerasConPermiso. Los permisos temporales llegan con `solicitudes`.

-- RF-AUTH-002: el contador de intentos se reinicia a las 6 horas del último fallo.
ALTER TABLE usuarios ADD COLUMN fecha_ultimo_intento_fallido TIMESTAMPTZ;
ALTER TABLE aspirantes ADD COLUMN fecha_ultimo_intento_fallido TIMESTAMPTZ;

CREATE TABLE user_career_permissions (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     INTEGER     NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
  career_id   INTEGER     NOT NULL REFERENCES carreras (id),
  assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  revoked_at  TIMESTAMPTZ,
  UNIQUE (user_id, career_id)
);

CREATE INDEX idx_permisos_carrera_activos ON user_career_permissions (user_id) WHERE revoked_at IS NULL;

CREATE TABLE codigos_verificacion (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  aspirante_id INTEGER      NOT NULL REFERENCES aspirantes (id) ON DELETE CASCADE,
  proposito    VARCHAR(30)  NOT NULL,
  codigo_hash  VARCHAR(255) NOT NULL,
  expira_en    TIMESTAMPTZ  NOT NULL,
  intentos     INTEGER      NOT NULL DEFAULT 0,
  usado_en     TIMESTAMPTZ
);

CREATE INDEX idx_codigos_aspirante ON codigos_verificacion (aspirante_id, proposito);

-- El id viaja firmado dentro del JWT de la cookie: cerrar la fila corta la sesión al instante.
CREATE TABLE sesiones (
  id           UUID PRIMARY KEY,
  titular_tipo VARCHAR(20) NOT NULL,
  titular_id   INTEGER     NOT NULL,
  ip           VARCHAR(45),
  user_agent   VARCHAR(500),
  inicio       TIMESTAMPTZ NOT NULL,
  ultimo_uso   TIMESTAMPTZ NOT NULL,
  expira_en    TIMESTAMPTZ NOT NULL,
  cerrada_en   TIMESTAMPTZ
);

CREATE INDEX idx_sesiones_titular ON sesiones (titular_tipo, titular_id);
