-- Sprint 3: solicitudes (RF-ASP-001), historial de estados (RF-ESTADO-003), documentos (RF-ACAD-009)
-- y permisos temporales (Requisitos v12 §5, tabla 4). Los campos marcados "Propuesta" salen del contrato de la API (§2).

-- Numera el código de expediente (EXP-2026-001). No se reinicia con el año.
CREATE SEQUENCE solicitudes_numero_exp_seq;

CREATE TABLE solicitudes (
  id                              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo_exp                      VARCHAR(20)  NOT NULL UNIQUE,
  aspirante_id                    INTEGER      NOT NULL REFERENCES aspirantes (id),
  carrera_destino_id              INTEGER      NOT NULL REFERENCES carreras (id),
  estado_codigo                   VARCHAR(50)  NOT NULL REFERENCES estados (codigo),  -- Propuesta: estado actual
  responsable_academico_id        INTEGER REFERENCES usuarios (id),
  responsable_administrativo_id   INTEGER REFERENCES usuarios (id),
  fecha_creacion                  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  fecha_ultima_mod                TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  fecha_ultimo_cambio_estado      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  fecha_asignacion_academico      TIMESTAMPTZ,
  fecha_asignacion_administrativo TIMESTAMPTZ,
  universidad_origen              VARCHAR(255) NOT NULL,  -- Propuesta
  facultad_origen                 VARCHAR(255) NOT NULL,  -- Propuesta
  carrera_origen                  VARCHAR(255) NOT NULL,  -- Propuesta
  condicion_academica             VARCHAR(50)  NOT NULL,  -- Propuesta: valores a definir
  observaciones                   TEXT                    -- Propuesta
);

CREATE INDEX idx_solicitudes_aspirante ON solicitudes (aspirante_id);
CREATE INDEX idx_solicitudes_carrera ON solicitudes (carrera_destino_id);
CREATE INDEX idx_solicitudes_estado ON solicitudes (estado_codigo);

CREATE TABLE estados_solicitud (
  id                        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitud_id              INTEGER     NOT NULL REFERENCES solicitudes (id) ON DELETE CASCADE,
  estado_codigo             VARCHAR(50) NOT NULL REFERENCES estados (codigo),
  estado_anterior_codigo    VARCHAR(50) REFERENCES estados (codigo),  -- Nulo en la creación
  fecha_asignacion          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  fecha_ultima_modificacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  usuario_ultimo_cambio_id  INTEGER REFERENCES usuarios (id),         -- Nulo si lo disparó el aspirante
  comentarios               TEXT
);

CREATE INDEX idx_estados_solicitud ON estados_solicitud (solicitud_id, fecha_asignacion DESC);

CREATE TABLE documentos_solicitud (
  id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitud_id          INTEGER      NOT NULL REFERENCES solicitudes (id) ON DELETE CASCADE,
  tipo                  VARCHAR(20)  NOT NULL,
  descripcion           VARCHAR(255),           -- Propuesta
  nombre_archivo        VARCHAR(255),           -- Nulo si es un requerido faltante
  ruta_archivo          VARCHAR(500),           -- Por año y DNI; nunca sale de la API
  tamano_bytes          INTEGER,
  fecha_carga           TIMESTAMPTZ,
  version               INTEGER      NOT NULL DEFAULT 1,
  reemplaza_a_id        INTEGER REFERENCES documentos_solicitud (id),
  estado_revision       VARCHAR(20)  NOT NULL DEFAULT 'PENDIENTE',
  etapa_revision        VARCHAR(20)  NOT NULL DEFAULT 'DOCUMENTACION',
  comentario_revision   TEXT,
  revisado_por_id       INTEGER REFERENCES usuarios (id),
  fecha_revision        TIMESTAMPTZ,
  es_requerido_faltante BOOLEAN      NOT NULL DEFAULT FALSE,
  borrador              BOOLEAN      NOT NULL DEFAULT TRUE  -- Propuesta: hasta ENVIAR_DOCUMENTACION
);

CREATE INDEX idx_documentos_solicitud ON documentos_solicitud (solicitud_id);

CREATE TABLE user_solicitud_permissions (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      INTEGER     NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
  solicitud_id INTEGER     NOT NULL REFERENCES solicitudes (id) ON DELETE CASCADE,
  assigned_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  assigned_by  INTEGER     NOT NULL REFERENCES usuarios (id),
  expires_at   TIMESTAMPTZ,  -- Nulo = sin vencimiento
  revoked_at   TIMESTAMPTZ,  -- Nulo = activo
  UNIQUE (user_id, solicitud_id)
);

CREATE INDEX idx_permisos_solicitud ON user_solicitud_permissions (solicitud_id);
