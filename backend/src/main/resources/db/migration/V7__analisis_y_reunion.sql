-- Sprint 5: análisis académico (RF-ACAD-002), rondas de fechas y reunión (RF-ASP-005, RF-ACAD-003).
-- `analisis_academico` sale de los requisitos; las otras tres son la propuesta del contrato de la API (§2.10 a §2.12).

CREATE TABLE analisis_academico (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitud_id   INTEGER      NOT NULL REFERENCES solicitudes (id) ON DELETE CASCADE,
  tipo           VARCHAR(30)  NOT NULL,           -- MATRIZ_EQUIVALENCIAS o HORARIO_CURSADA
  version        INTEGER      NOT NULL DEFAULT 1, -- La vigente es la mayor por solicitud y tipo
  reemplaza_a_id INTEGER REFERENCES analisis_academico (id),
  nombre_archivo VARCHAR(255),                    -- Archivo, notas o las dos cosas
  ruta_archivo   VARCHAR(500),
  notas          TEXT,
  fecha_carga    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  subido_por_id  INTEGER      NOT NULL REFERENCES usuarios (id)
);

CREATE INDEX idx_analisis_solicitud ON analisis_academico (solicitud_id);

CREATE TABLE rondas_reunion (
  id                       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitud_id             INTEGER     NOT NULL REFERENCES solicitudes (id) ON DELETE CASCADE,
  numero                   INTEGER     NOT NULL,  -- 1 o 2
  propuesta_por_id         INTEGER     NOT NULL REFERENCES usuarios (id),
  fecha_propuesta          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  motivo_otras_fechas      TEXT,                  -- Lo que escribe el aspirante al pedir otras fechas
  disponibilidad_aspirante TEXT,
  rechazada                BOOLEAN     NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_rondas_solicitud ON rondas_reunion (solicitud_id);

CREATE TABLE horarios_propuestos (
  id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ronda_id INTEGER     NOT NULL REFERENCES rondas_reunion (id) ON DELETE CASCADE,
  inicio   TIMESTAMPTZ NOT NULL,
  fin      TIMESTAMPTZ NOT NULL,
  elegido  BOOLEAN     NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_horarios_ronda ON horarios_propuestos (ronda_id);

CREATE TABLE reuniones (
  id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitud_id         INTEGER     NOT NULL REFERENCES solicitudes (id) ON DELETE CASCADE,
  inicio               TIMESTAMPTZ NOT NULL,
  fin                  TIMESTAMPTZ NOT NULL,
  origen               VARCHAR(20) NOT NULL,      -- ELEGIDA_ASPIRANTE o FIJADA_CHAT
  horario_propuesto_id INTEGER REFERENCES horarios_propuestos (id),
  enlace_meet          VARCHAR(500),
  notas                TEXT,
  resultado            VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',  -- PENDIENTE, REALIZADA o NO_ASISTIO
  fecha_resultado      TIMESTAMPTZ
);

CREATE INDEX idx_reuniones_solicitud ON reuniones (solicitud_id);
