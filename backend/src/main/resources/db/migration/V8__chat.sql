-- Sprint 6: chat de la solicitud (RF-MSG-001 a 004, contrato §2.16).

CREATE TABLE mensajes_chat (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitud_id   INTEGER      NOT NULL REFERENCES solicitudes (id) ON DELETE CASCADE,
  autor_tipo     VARCHAR(20)  NOT NULL,           -- USUARIO o ASPIRANTE
  autor_id       INTEGER      NOT NULL,
  contenido      VARCHAR(500) NOT NULL,           -- Vacío si el mensaje es solo un adjunto
  tipo_consulta  VARCHAR(20)  NOT NULL,           -- DOCUMENTACION, ESTADO, CALCULOS, FECHAS u OTRO
  adjunto_nombre VARCHAR(255),
  adjunto_ruta   VARCHAR(500),
  fecha_envio    TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_mensajes_solicitud ON mensajes_chat (solicitud_id, id);

-- Hasta qué mensaje leyó cada participante del chat: de acá salen "visto" y los no leídos.
CREATE TABLE lecturas_chat (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitud_id     INTEGER     NOT NULL REFERENCES solicitudes (id) ON DELETE CASCADE,
  lector_tipo      VARCHAR(20) NOT NULL,          -- USUARIO o ASPIRANTE
  lector_id        INTEGER     NOT NULL,
  hasta_mensaje_id INTEGER     NOT NULL,
  fecha_lectura    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (solicitud_id, lector_tipo, lector_id)
);
