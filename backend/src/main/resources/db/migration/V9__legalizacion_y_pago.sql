-- Sprint 7: informe de materias (RF-ASP-006), cupón de pago (RF-SEC-001) y comprobantes (RF-ASP-007, RF-SEC-002).

-- Lo carga el Académico al aceptar los documentos legalizados: una fila por solicitud.
CREATE TABLE informes_materias (
  id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitud_id         INTEGER       NOT NULL UNIQUE REFERENCES solicitudes (id) ON DELETE CASCADE,
  materias_reconocidas INTEGER       NOT NULL,
  observaciones        VARCHAR(2000),
  cargado_por_id       INTEGER       NOT NULL REFERENCES usuarios (id),
  fecha_carga          TIMESTAMPTZ   NOT NULL DEFAULT NOW()
);

-- El PDF lo genera el sistema con el monto que indica Secretaría.
CREATE TABLE cupones_pago (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitud_id   INTEGER        NOT NULL UNIQUE REFERENCES solicitudes (id) ON DELETE CASCADE,
  monto          NUMERIC(12, 2) NOT NULL,
  ruta_archivo   VARCHAR(500)   NOT NULL,
  emitido_por_id INTEGER        NOT NULL REFERENCES usuarios (id),
  fecha_emision  TIMESTAMPTZ    NOT NULL DEFAULT NOW()
);

-- Cada reenvío suma una versión; las anteriores se conservan con su verificación.
CREATE TABLE comprobantes_pago (
  id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitud_id          INTEGER      NOT NULL REFERENCES solicitudes (id) ON DELETE CASCADE,
  cupon_id              INTEGER      NOT NULL REFERENCES cupones_pago (id) ON DELETE CASCADE,
  version               INTEGER      NOT NULL,
  nombre_archivo        VARCHAR(255) NOT NULL,
  ruta_archivo          VARCHAR(500) NOT NULL,
  tamano_bytes          INTEGER      NOT NULL,
  fecha_carga           TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  estado_verificacion   VARCHAR(20)  NOT NULL DEFAULT 'PENDIENTE',  -- PENDIENTE, ACEPTADO o RECHAZADO
  comentario_secretaria VARCHAR(500),
  verificado_por_id     INTEGER REFERENCES usuarios (id),
  fecha_verificacion    TIMESTAMPTZ,
  UNIQUE (solicitud_id, version)
);
